// Fails the build when a translation file is missing keys, has extra keys,
// or doesn't cover every section and image caption the story needs.
// en.json is the reference; every other src/i18n/*.json must match its shape.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../src/i18n/", import.meta.url));
const story = JSON.parse(readFileSync(new URL("../src/data/story.json", import.meta.url), "utf8"));
const LANG_FILE = /^[a-z]{2,3}(-[A-Za-z0-9]{2,8})?\.json$/;

function shape(value, path = "") {
  if (Array.isArray(value)) {
    // Arrays of paragraphs may differ in length between languages; only the type must match.
    return [[path, "array"]];
  }
  if (value && typeof value === "object") {
    return Object.entries(value).flatMap(([k, v]) => shape(v, path ? `${path}.${k}` : k));
  }
  return [[path, typeof value]];
}

const files = readdirSync(dir).filter((f) => f.endsWith(".json"));
const errors = [];
for (const f of files) if (!LANG_FILE.test(f)) errors.push(`${f}: file name must be a language code, e.g. de.json or zh-Hans.json`);

const ref = JSON.parse(readFileSync(dir + "en.json", "utf8"));
const refShape = new Map(shape(ref));

for (const f of files) {
  let data;
  try {
    data = JSON.parse(readFileSync(dir + f, "utf8"));
  } catch (e) {
    errors.push(`${f}: invalid JSON (${e.message})`);
    continue;
  }
  const s = new Map(shape(data));
  for (const [k, t] of refShape) {
    if (!s.has(k)) errors.push(`${f}: missing "${k}"`);
    else if (s.get(k) !== t) errors.push(`${f}: "${k}" should be ${t}, is ${s.get(k)}`);
  }
  for (const k of s.keys()) if (!refShape.has(k)) errors.push(`${f}: unknown key "${k}"`);

  for (const sec of story.sections) {
    const t = data.sections?.[sec.id];
    if (!t) continue; // already reported above
    for (const img of sec.images ?? []) {
      if (img.caption && !t.captions?.[img.src]) errors.push(`${f}: missing caption sections.${sec.id}.captions.${img.src}`);
    }
    for (const [i, p] of (t.body ?? []).entries()) {
      if (typeof p !== "string" || !p.trim()) errors.push(`${f}: sections.${sec.id}.body[${i}] is empty`);
    }
  }
}

if (errors.length) {
  console.error(`Translation check failed:\n  ${errors.join("\n  ")}`);
  process.exit(1);
}
// The visit counter only accepts languages that exist; generate its allow-list from the same files.
const codes = files.map((f) => f.replace(".json", "")).sort();
writeFileSync(
  new URL("../functions/_languages.ts", import.meta.url),
  `// Generated by scripts/check-i18n.mjs from src/i18n/*.json. Do not edit.\nexport const LANGUAGES: readonly string[] = ${JSON.stringify(codes)};\n`,
);
console.log(`Translations OK: ${files.map((f) => f.replace(".json", "")).join(", ")}`);
